// Clones keep the route's fixed height; re-fit after changing content and stretch overlays to match.
function refitClone(f) {
  finalize(f);
  for (const o of f.children.filter((c) => c.name.startsWith('Overlay ·'))) { o.resize(390, f.height); for (const k of o.children) { if (k.name === 'Scrim') k.resize(390, f.height); else k.y = Math.max(0, f.height - k.height); } }
}

