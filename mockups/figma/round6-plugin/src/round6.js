const TYPE = { 'Display/Amount': [40, 48], 'Display/Balance': [28, 34], 'Title/Screen': [20, 26], 'Title/Bar': [17, 22], 'Figure/Large': [16, 22], 'Heading/Section': [15, 20], 'Label/Small': [13, 18] };
async function syncSizes() {
  const out = [];
  for (const [key, [size, lh]] of Object.entries(TYPE)) {
    const st = await getStyle(S[key]); if (!st) continue;
    if (st.fontSize !== size) { await figma.loadFontAsync(st.fontName); st.fontSize = size; st.lineHeight = { unit: 'PIXELS', value: lh }; out.push(`${key} ${size}`); }
  }
  for (const id of [C.chip.False, C.chip.True]) { const v = await figma.getNodeByIdAsync(id); setH(v, 36); v.paddingLeft = 9; v.paddingRight = 12; v.itemSpacing = 6; }
  const chipSet = (await figma.getNodeByIdAsync(C.chip.True)).parent; if (chipSet) chipSet.description = 'Choice chip: 36px visible, 44px tap area in code (an invisible layer). Selected = brand/soft fill, brand/ink border, brand/deep text.';
  for (const id of [C.segment.False, C.segment.True]) { const v = await figma.getNodeByIdAsync(id); v.resize(Math.max(48, v.width), 36); }
  const buttons = await figma.getNodeByIdAsync(C.buttonSet);
  for (const v of buttons.children) { if (/Size=Medium/.test(v.name)) setH(v, 40); else v.resize(v.width, 48); }
  buttons.description = 'Large 48px (full width), Medium 40px. In code every button keeps a 44px tap area.';
  const tb = await figma.getNodeByIdAsync(C.topBar.id); const action = tb.findOne((n) => n.name === 'Action'); if (action) setH(action, 40);
  out.push('chip/segment 36 · button 40/48 · top-bar action 40');
  // Local size overrides left by earlier rounds (big amounts in sheets and hero rows).
  let fixed = 0;
  for (const pid of [PAGES.components, PAGES.screens]) {
    const page = await figma.getNodeByIdAsync(pid); await page.loadAsync();
    for (const t of page.findAllWithCriteria({ types: ['TEXT'] })) {
      if (typeof t.fontSize !== 'number' || ![26, 28].includes(t.fontSize)) continue;
      if (t.fontName === figma.mixed) continue;
      await figma.loadFontAsync(t.fontName); t.fontSize = t.fontSize === 26 ? 22 : 24; fixed++;
    }
  }
  out.push(`${fixed} large amount override(s) stepped down`);
  return out.join(' · ');
}
async function refitRoutes() {
  let n = 0;
  for (const id of ROUTE_SECTIONS) {
    const sec = await figma.getNodeByIdAsync(id); if (!sec) continue;
    for (const f of sec.children) if (f.type === 'FRAME' && f.children.some((c) => c.name === 'Content')) { finalize(f); n++; }
    fitSection(sec);
  }
  return `${n} screens re-fitted`;
}

