async function cleanRoutes() {
  let n = 0;
  for (const id of ROUTE_SECTIONS) {
    const sec = await figma.getNodeByIdAsync(id); if (!sec) continue;
    for (const f of sec.children) for (const x of f.findAll((k) => /\(show to review\)$/.test(k.name))) { x.remove(); n++; }
  }
  return `${n} hidden review layer(s) removed`;
}

