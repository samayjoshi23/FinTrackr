function startingPoints() {
  const pts = [['Login', 'Sign in'], ['Home · Dashboard', 'Signed in']].filter(([n]) => route[n]).map(([n, name]) => ({ nodeId: route[n].id, name }));
  figma.currentPage.flowStartingPoints = pts; return `${pts.length} flow starting point(s): ${pts.map((p) => p.name).join(', ')}`;
}
function scrolling() {
  let n = 0; for (const f of [...Object.values(route), ...Object.values(stateFrames)]) { try { f.overflowDirection = 'VERTICAL'; n++; } catch { /* not a scrollable frame */ } }
  return `${n} frames scroll vertically when taller than the phone`;
}

