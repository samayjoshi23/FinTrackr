async function wireComponents() {
  const log = [];
  const tb = await figma.getNodeByIdAsync(C.topBar.id); const back = tb.findOne((n) => n.name === 'Back');
  if (back) { await back.setReactionsAsync([{ trigger: { type: 'ON_CLICK' }, actions: [{ type: 'BACK' }] }]); notes.set++; log.push('Back → previous screen'); }
  const set = await figma.getNodeByIdAsync('4:102');
  const dest = { 'Tab Home': ['Home · Dashboard', 'fade'], 'Tab Transactions': ['Transactions', 'fade'], 'Tab Groups': ['Groups', 'fade'], 'Tab Settings': ['Settings', 'fade'], 'Add button': ['Add transaction', 'push'] };
  let n = 0;
  for (const variant of set ? set.children : []) for (const item of variant.children) {
    const d = dest[item.name]; if (!d) continue;
    const r = reaction({ to: d[0], t: d[1], label: item.name }); if (!r) continue;
    try { await item.setReactionsAsync([r]); notes.set++; n++; } catch (e) { notes.failed.push(`Bottom nav ${item.name} — ${e.message}`); }
  }
  log.push(`bottom nav: ${n} tab links on the component (all instances inherit them)`);
  return log.join(' · ');
}

