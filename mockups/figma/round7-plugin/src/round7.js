// FinTrackr UI v2 · Round 7 — Figma prototype wiring.
// Adds tap interactions (prototype links) to the existing frames; it never adds, removes or moves a frame.
//   • Bottom nav tabs, the Add button and every top-bar Back arrow are wired once, on the components.
//   • Each route screen links to the screen the same action opens in the app (Login → Home, a budget row →
//     Transactions, Edit → Edit screen, a menu row → its page…).
//   • Popovers, sheets and pickers open their state frame from "07 · States"; Cancel / Keep it / the scrim /
//     the close button go back, and each sheet's confirm button lands on the screen the app returns to.
//   • Flow starting points: "Sign in" (Login) and "Signed in" (Home).
// Present with the ▶ button. Safe to run again: each wired layer's interactions are replaced, not added to.
// code.js is generated by ../build.mjs; edit this file or ../shared/prelude.js.

/*__PRELUDE__*/

const BTN = 'Button'; // the Button component's name (a spec with kind: BTN only matches a real button)
const route = {}, stateFrames = {};
const notes = { set: 0, unresolved: [], missing: [], failed: [] };

// ---------------------------------------------------------------------------------------------
// Reactions
// ---------------------------------------------------------------------------------------------
const EASE = { type: 'EASE_OUT' };
const TRANSITIONS = {
  push: { type: 'PUSH', direction: 'LEFT', matchLayers: false, duration: 0.25, easing: EASE },
  fade: { type: 'DISSOLVE', duration: 0.15, easing: EASE },
  state: { type: 'SMART_ANIMATE', duration: 0.2, easing: EASE }, // popovers/sheets: the new layers fade in over the same screen
};
const lookup = (name) => route[name] || stateFrames[name] || null;
function reaction(spec) {
  if (spec.back) return { trigger: { type: 'ON_CLICK' }, actions: [{ type: 'BACK' }] };
  const dest = lookup(spec.to);
  if (!dest) { notes.unresolved.push(`${spec.to} (${spec.label || spec.text || spec.name || spec.inst || 'target'})`); return null; }
  const isState = !!stateFrames[spec.to];
  return { trigger: { type: 'ON_CLICK' }, actions: [{ type: 'NODE', destinationId: dest.id, navigation: 'NAVIGATE', transition: TRANSITIONS[spec.t || (isState ? 'state' : 'push')], preserveScrollPosition: false }] };
}
async function apply(node, spec, where) {
  const r = reaction(spec); if (!r) return;
  try { await node.setReactionsAsync([r]); notes.set++; }
  catch (e) { notes.failed.push(`${where}: ${spec.text || spec.name || spec.inst || 'layer'} — ${e.message}`); }
}

// ---------------------------------------------------------------------------------------------
// Finding the layer a tap should land on
// ---------------------------------------------------------------------------------------------
const CHROME = /^(Top bar|Bottom nav|Active=)/;
const CLICKABLE = /^(Action$|Icon button|Text button|Account switcher|Period$|Add button|Tab )/;
const instCache = new Map();
async function setName(inst) {
  if (instCache.has(inst.id)) return instCache.get(inst.id);
  let name = inst.name;
  try { const mc = await inst.getMainComponentAsync(); if (mc) name = mc.parent && mc.parent.type === 'COMPONENT_SET' ? mc.parent.name : mc.name; } catch { /* keep the layer name */ }
  instCache.set(inst.id, name); return name;
}
async function hitOf(n, root, up = 0) {
  if (up) { let p = n; for (let i = 0; i < up && p.parent; i++) p = p.parent; return p; }
  for (let p = n; p && p !== root; p = p.parent) {
    if (p.type === 'INSTANCE' && !CHROME.test(p.name)) return p;
    if (p.type !== 'TEXT' && CLICKABLE.test(p.name)) return p;
  }
  // A bare text link: tap its row, but never a whole screen-level container.
  const par = n.parent;
  return !par || par === root || par.name === 'Content' || par.name === 'Footer' ? n : par;
}
function scopeRoots(f, scope) {
  if (!scope) return [f];
  if (scope === 'overlay') return f.children.filter((c) => c.name.startsWith('Overlay ·'));
  return f.children.filter((c) => c.name.startsWith(scope));
}
// spec: text | textRe | name | nameRe | inst (component name) | in+first | child — plus scope, up, kind, all
async function targets(f, spec) {
  const out = []; const roots = scopeRoots(f, spec.scope);
  for (const root of roots) {
    if (spec.text != null || spec.textRe) {
      const texts = root.findAll((n) => n.type === 'TEXT' && (spec.text != null ? n.characters === spec.text : spec.textRe.test(n.characters)));
      for (const t of texts) {
        const h = await hitOf(t, root, spec.up || 0);
        if (spec.kind && !(h.type === 'INSTANCE' && (await setName(h)) === spec.kind)) continue;
        out.push(h);
      }
    } else if (spec.name != null || spec.nameRe) {
      out.push(...root.findAll((n) => (spec.name != null ? n.name === spec.name : spec.nameRe.test(n.name))));
    } else if (spec.inst) {
      for (const n of root.findAll((x) => x.type === 'INSTANCE')) if ((await setName(n)) === spec.inst) out.push(n);
    } else if (spec.in) {
      const box = root.findOne((n) => n.name === spec.in);
      if (box) { const kids = spec.child ? box.children.filter((c) => c.name === spec.child) : box.findAll((n) => n.type === 'INSTANCE'); out.push(...(spec.all ? kids : kids.slice(0, 1))); }
    }
  }
  const uniq = [...new Set(out)];
  return spec.all || spec.text == null && spec.textRe == null ? uniq : uniq.slice(0, 1);
}
async function wire(frameName, specs) {
  const f = route[frameName] || stateFrames[frameName];
  if (!f) { notes.missing.push(`frame "${frameName}"`); return; }
  for (const spec of specs) {
    const nodes = await targets(f, spec);
    if (!nodes.length) { notes.missing.push(`${frameName}: ${spec.label || spec.text || spec.textRe || spec.name || spec.nameRe || spec.inst || spec.in}`); continue; }
    for (const n of nodes) await apply(n, spec, frameName);
  }
}
const footerBtn = (to, extra = {}) => ({ in: 'Footer', to, label: 'footer button', ...extra });
const topAction = (text, to) => ({ text, scope: 'Top bar', to });
const SCRIM = [{ name: 'Scrim', back: true, scope: 'overlay', label: 'scrim' }, { name: 'Icon button · Close', back: true, scope: 'overlay', label: 'close' }];

