async function syncType() {
  const log = [];
  let semi = { family: 'Space Grotesk', style: 'SemiBold' };
  try { await figma.loadFontAsync(semi); } catch { semi = { family: 'Space Grotesk', style: 'Bold' }; await figma.loadFontAsync(semi); }
  for (const key of ['Display/Amount', 'Display/Balance', 'Title/Screen', 'Title/Bar']) {
    const st = await getStyle(S[key]); if (!st) continue;
    if (st.fontName.style !== semi.style) { await figma.loadFontAsync(st.fontName); st.fontName = semi; log.push(`${key} → ${semi.style}`); }
  }
  const label = await getStyle(S['Label/Small']);
  if (label && label.fontSize !== 14) { await figma.loadFontAsync(label.fontName); label.fontSize = 14; label.lineHeight = { unit: 'PIXELS', value: 20 }; log.push('Label/Small → 14/20'); }
  // Selected chip: text and icon in the deep green the mockup uses.
  const on = await figma.getNodeByIdAsync(C.chip.True);
  for (const t of on.findAllWithCriteria({ types: ['TEXT'] })) t.fills = [fill('brand/deep')];
  for (const v of on.findAllWithCriteria({ types: ['VECTOR'] })) v.strokes = [fill('brand/deep')];
  log.push('Chip selected → brand/deep');
  return log.join(' · ') || 'already matching';
}

