const hexToRgba = (h) => { const n = h.replace('#', ''); const v = (i) => parseInt(n.slice(i, i + 2), 16) / 255; return { r: v(0), g: v(2), b: v(4), a: n.length === 8 ? v(6) : 1 }; };
const close = (a, b) => Math.abs(a.r - b.r) < 0.006 && Math.abs(a.g - b.g) < 0.006 && Math.abs(a.b - b.b) < 0.006 && Math.abs((a.a ?? 1) - (b.a ?? 1)) < 0.01;
