async function syncColours() {
  const first = await figma.variables.getVariableByIdAsync(V['brand/emerald']);
  const coll = await figma.variables.getVariableCollectionByIdAsync(first.variableCollectionId);
  const mode = coll.defaultModeId;
  let changed = 0;
  for (const [name, hex] of Object.entries(TOKENS)) {
    const v = vars[name] || (vars[name] = await figma.variables.getVariableByIdAsync(V[name]));
    if (!v) { colourLog.push(`missing variable ${name}`); continue; }
    const want = hexToRgba(hex); const have = v.valuesByMode[mode];
    if (!have || !close(have, want)) { colourLog.push(`${name}: ${have ? toHex(have) : '—'} → ${hex}`); v.setValueForMode(mode, want); changed++; }
  }
  const local = await figma.variables.getLocalVariablesAsync('COLOR');
  let added = 0;
  for (const [name, hex] of Object.entries(NEW_TOKENS)) {
    let v = local.find((x) => x.name === name && x.variableCollectionId === coll.id);
    if (!v) { v = figma.variables.createVariable(name, coll, 'COLOR'); added++; colourLog.push(`added ${name} ${hex}`); }
    v.setValueForMode(mode, hexToRgba(hex));
    vars[name] = v;
  }
  return `${changed} variable value(s) corrected, ${added} token(s) added`;
}

// Bind loose paints that equal a token; list the rest. Layers inside instances are left alone (they follow
// their main component).
async function bindLoosePaints() {
  const palette = Object.entries({ ...TOKENS, ...NEW_TOKENS }).map(([k, h]) => [k, hexToRgba(h)]);
  const insideInstance = (n) => { for (let p = n.parent; p; p = p.parent) if (p.type === 'INSTANCE') return true; return false; };
  let bound = 0; const off = new Map();
  for (const pageId of [PAGES.components, PAGES.screens]) {
    const page = await figma.getNodeByIdAsync(pageId); await page.loadAsync();
    const nodes = page.findAll((n) => n.type !== 'SECTION' && ('fills' in n || 'strokes' in n));
    for (const n of nodes) {
      if (insideInstance(n)) continue;
      for (const prop of ['fills', 'strokes']) {
        const paints = n[prop]; if (!Array.isArray(paints) || !paints.length) continue;
        let touched = false;
        const next = paints.map((p) => {
          if (p.type !== 'SOLID' || p.boundVariables?.color || p.visible === false) return p;
          const c = { ...p.color, a: p.opacity ?? 1 };
          const hit = palette.find(([, t]) => close({ ...c, a: 1 }, { ...t, a: 1 }));
          if (hit && (p.opacity ?? 1) === 1) { touched = true; bound++; return figma.variables.setBoundVariableForPaint(p, 'color', vars[hit[0]]); }
          const key = `${toHex(p.color)}${(p.opacity ?? 1) < 1 ? ` @${Math.round((p.opacity ?? 1) * 100)}%` : ''}`;
          off.set(key, (off.get(key) || 0) + 1); return p;
        });
        if (touched) n[prop] = next;
      }
    }
  }
  const offList = [...off.entries()].sort((a, b) => b[1] - a[1]);
  colourLog.push(`bound ${bound} loose paint(s) to tokens`);
  colourLog.push(...offList.map(([k, n]) => `off-palette ${k} × ${n}`));
  return `${bound} paint(s) bound; ${offList.length} off-palette colour(s) listed on Read me`;
}

