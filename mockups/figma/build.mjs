// Generates each plugin's code.js (the file Figma runs) from its src/ file, the shared prelude and,
// for round 3, the Read me page body. Run: node mockups/figma/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const here = (p) => new URL(p, import.meta.url);
const read = (p) => readFileSync(here(p), 'utf8');
const prelude = read('./shared/prelude.js');
const readme = read('./readme-page.js')
  .split('\n')
  .filter((l) => !l.startsWith('//') && !l.startsWith('return '))
  .join('\n')
  .replace('Updated 24 Oct 2026.', 'Updated 24 Oct 2026 (round 3: placement and 44px targets).')
  .replace('an account pill (“Ghar · SJ”) that opens Settings', 'an account pill (“Ghar · SJ”) that opens the account switcher');

for (const name of ['round3', 'round4', 'round5', 'round6', 'round7']) {
  let src = read(`./${name}-plugin/src/${name}.js`);
  if (!src.includes('/*__PRELUDE__*/')) throw new Error(`prelude marker missing in ${name}`);
  src = src.replace('/*__PRELUDE__*/', prelude).replace('/*__README_BODY__*/', readme.trim().replace(/\n/g, '\n  '));
  src = src.replaceAll('figma.createAutoLayout(', 'createAutoLayout('); // figma is frozen in plugins
  writeFileSync(here(`./${name}-plugin/code.js`), `// GENERATED by mockups/figma/build.mjs — edit ${name}-plugin/src/${name}.js or shared/prelude.js instead.\n${src}`);
  console.log(`wrote ${name}-plugin/code.js`);
}
