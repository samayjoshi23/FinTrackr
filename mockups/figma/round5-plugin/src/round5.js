// October 2026: the 1st is a Thursday (Monday-first column 3); today is the 23rd.
const MONTH = { lead: 3, days: 31, today: 23 };
async function dayCell(d, st) {
  const c = row(0, `Day ${d}`); c.resize(50, 44); c.primaryAxisSizingMode = 'FIXED'; c.counterAxisSizingMode = 'FIXED'; c.primaryAxisAlignItems = 'CENTER'; c.clipsContent = false;
  if (st.band) { const b = figma.createRectangle(); b.name = 'Range band'; b.fills = [fill('brand/soft')]; c.appendChild(b); b.layoutPositioning = 'ABSOLUTE'; b.y = 0; if (st.band === 'mid') { b.x = 0; b.resize(50, 44); } else if (st.band === 'start') { b.x = 25; b.resize(25, 44); } else { b.x = 0; b.resize(25, 44); } }
  const dot = row(0, 'Day'); dot.resize(40, 40); dot.primaryAxisSizingMode = 'FIXED'; dot.counterAxisSizingMode = 'FIXED'; dot.primaryAxisAlignItems = 'CENTER'; dot.cornerRadius = 999;
  if (st.selected) dot.fills = [fill('brand/ink')];
  if (st.today && !st.selected) { dot.strokes = [fill('brand/ink')]; dot.strokeWeight = 1.5; dot.strokeAlign = 'INSIDE'; }
  dot.appendChild(await text(String(d), 'Figure/Body', st.selected ? 'text/on-brand' : st.disabled ? 'text/disabled' : 'text/primary'));
  c.appendChild(dot); return c;
}
async function calendar({ selected = [], range = null, max = MONTH.today }) {
  const g = col(2, 'Calendar');
  const head = row(0, 'Weekdays'); add(g, head, false);
  for (const w of ['M', 'T', 'W', 'T', 'F', 'S', 'S']) { const h = row(0, w); h.resize(50, 32); h.primaryAxisSizingMode = 'FIXED'; h.counterAxisSizingMode = 'FIXED'; h.primaryAxisAlignItems = 'CENTER'; h.appendChild(await text(w, 'Body/Small', 'text/muted')); head.appendChild(h); }
  let week = null;
  for (let i = 0; i < MONTH.lead + MONTH.days; i++) {
    if (i % 7 === 0) { week = row(0, `Week ${i / 7 + 1}`); add(g, week, false); }
    if (i < MONTH.lead) { const e = figma.createFrame(); e.name = 'Empty'; e.resize(50, 44); e.fills = []; week.appendChild(e); continue; }
    const d = i - MONTH.lead + 1;
    const inRange = range && d > range[0] && d < range[1];
    week.appendChild(await dayCell(d, { selected: selected.includes(d), today: d === MONTH.today, disabled: d > max,
      band: range ? (inRange ? 'mid' : d === range[0] ? 'start' : d === range[1] ? 'end' : null) : null }));
  }
  return g;
}
