const log = [];

async function ensureToken(name, hex) {
  if (vars[name]) return;
  const first = vars['brand/emerald'];
  const coll = await figma.variables.getVariableCollectionByIdAsync(first.variableCollectionId);
  const n = hex.replace('#', ''); const ch = (i) => parseInt(n.slice(i, i + 2), 16) / 255;
  const v = figma.variables.createVariable(name, coll, 'COLOR'); v.setValueForMode(coll.defaultModeId, { r: ch(0), g: ch(2), b: ch(4), a: 1 });
  vars[name] = v; log.push(`added ${name} ${hex}`);
}
function refit(f) {
  finalize(f);
  for (const o of f.children.filter((c) => c.name.startsWith('Overlay ·'))) {
    o.resize(390, f.height);
    for (const k of o.children) { if (k.name === 'Scrim') k.resize(390, f.height); else k.y = Math.max(0, f.height - k.height); }
  }
  fitSection(f.parent);
}

