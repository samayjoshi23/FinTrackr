async function placeStates(k) {
  const out = [];
  // Transactions: loading below the filters; offline banner in the flow (pushes content when shown).
  const tx = await frameIn(SECTIONS.core, 'Transactions'); removeStates(tx);
  const who = tx.findOne((n) => n.type === 'FRAME' && n.name === 'Out by person');
  const top = who ? relY(who, tx) : 180;
  const footer = tx.children.find((c) => c.name === 'Footer');
  const L = stateLayer(tx, 'Loading', top, 'Footer'); if (footer) tx.insertChild(tx.children.indexOf(footer), L);
  for (let i = 0; i < 3; i++) { const d = k.skDay.createInstance(); add(L, d); }
  L.visible = false;
  const body = tx.children.find((c) => c.name === 'Content');
  const off = k.offline.createInstance(); off.name = 'State · Offline banner (show to review)'; body.insertChild(0, off); off.layoutSizingHorizontal = 'FILL'; off.visible = false;
  overlay(tx, k.range, 'Custom range');
  out.push('Transactions: loading, offline, custom range');
  // Home: everything under the greeting.
  const home = await frameIn(SECTIONS.core, 'Home · Dashboard'); removeStates(home);
  const sum = home.findOne((n) => n.type === 'FRAME' && n.name === 'Summary card');
  const H = stateLayer(home, 'Loading', sum ? relY(sum, home) : 90); H.itemSpacing = 20;
  add(H, await skeletonSummary()); const b = newCard('Bills skeleton'); add(H, b); for (let i = 0; i < 2; i++) { const r = k.skRow.createInstance(); add(b, r); if (i) ruleTop(r); }
  add(H, k.skDay.createInstance()); H.visible = false;
  out.push('Home: loading');
  // Recurring list.
  const rec = await frameIn(SECTIONS.recurring, 'Recurring'); removeStates(rec);
  const R = stateLayer(rec, 'Loading', 64); R.itemSpacing = 20; pad(R, 4, 20);
  add(R, await skeletonSummary()); const rc = newCard('List skeleton'); add(R, rc); for (let i = 0; i < 5; i++) { const r = k.skRow.createInstance(); add(rc, r); if (i) ruleTop(r); }
  R.visible = false; out.push('Recurring: loading');
  // Add transaction: date picker overlay + saving button over the save button.
  const addTx = await frameIn(SECTIONS.core, 'Add transaction'); removeStates(addTx);
  overlay(addTx, k.single, 'Date');
  const ft = addTx.children.find((c) => c.name === 'Footer');
  if (ft) { const s = k.saving.createInstance(); s.name = 'State · Saving (show to review)'; ft.appendChild(s); s.layoutPositioning = 'ABSOLUTE'; s.x = 20; s.y = 12; s.visible = false; }
  out.push('Add transaction: date, saving');
  return out.join(' · ');
}

