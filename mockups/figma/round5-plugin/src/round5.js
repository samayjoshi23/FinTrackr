async function dayHead(str) {
  const [day, ...rest] = str.split(' · ');
  const r = row(12, `Day · ${day}`); r.primaryAxisAlignItems = 'SPACE_BETWEEN'; r.counterAxisAlignItems = 'BASELINE'; pad(r, 14, 2, 8, 2);
  r.appendChild(await text(day, 'Label/Small', 'text/primary'));
  if (rest.length) r.appendChild(await text(rest.join(' · '), 'Body/Small', 'text/muted'));
  return r;
}
// Rows after `skip` header children move into cards; a TEXT child (a day label) closes the card and
// becomes a day header on the ground. The first row in each card loses its top rule.
async function cardify(container, { skip = 1, dayLabels = false } = {}) {
  if (container.children.some((c) => c.name === 'Day card')) return 0;
  const kids = container.children.slice(skip);
  let card = null, cards = 0;
  for (const k of kids) {
    if (k.type === 'TEXT') {
      card = null;
      if (dayLabels) { const h = await dayHead(k.characters); container.insertChild(container.children.indexOf(k), h); h.layoutSizingHorizontal = 'FILL'; k.remove(); }
      continue;
    }
    let first = false;
    if (!card) { card = newCard(); container.insertChild(container.children.indexOf(k), card); card.layoutSizingHorizontal = 'FILL'; cards++; first = true; }
    card.appendChild(k); k.layoutSizingHorizontal = 'FILL';
    if ('strokeTopWeight' in k) k.strokeTopWeight = first ? 0 : 1;
    if (k.type === 'FRAME' && k.layoutMode === 'HORIZONTAL' && k.paddingTop < 12) { k.paddingTop = 12; k.paddingBottom = 12; }
  }
  container.itemSpacing = dayLabels ? 0 : container.itemSpacing;
  return cards;
}
async function cardLists() {
  const out = [];
  // the row component: 64px tall (the card supplies the side padding)
  for (const id of [C.txRow.Expense, C.txRow.Income]) { const v = await figma.getNodeByIdAsync(id); v.resize(v.width, 64); }
  const tx = await frameIn(SECTIONS.core, 'Transactions');
  const list = tx.findOne((n) => n.type === 'FRAME' && n.name === 'List');
  out.push(`Transactions ${await cardify(list, { skip: 0, dayLabels: true })} day card(s)`); refit(tx);
  const home = await frameIn(SECTIONS.core, 'Home · Dashboard');
  const recent = home.findOne((n) => n.type === 'FRAME' && n.name === 'Recent transactions');
  const bills = home.findOne((n) => n.type === 'FRAME' && n.name === 'Upcoming bills');
  out.push(`Home ${await cardify(recent, { skip: 1, dayLabels: true })} + ${await cardify(bills, { skip: 1 })} card(s)`); refit(home);
  const rec = await frameIn(SECTIONS.recurring, 'Recurring');
  let n = 0; for (const name of ['Needs attention', 'Coming up', 'Paused']) { const s = rec.findOne((x) => x.type === 'FRAME' && x.name === name); if (s) n += await cardify(s, { skip: 1 }); }
  out.push(`Recurring ${n} card(s)`); refit(rec);
  const view = await frameIn(SECTIONS.recurring, 'View recurring');
  const pay = view.findOne((x) => x.type === 'FRAME' && x.name === 'Payments');
  if (pay) { await cardify(pay, { skip: 1 }); refit(view); out.push('Payments 1 card'); }
  return out.join(' · ');
}

